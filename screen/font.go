// font5x7 holds the compiled glyphs: bit 4 of each byte is the leftmost
// pixel of that row.
var font5x7 = map[byte][7]byte{}

func init() {
	for ch, rows := range fontSrc {
		var g [7]byte
		for r, row := range rows {
			var b byte
			for c := 0; c < 5 && c < len(row); c++ {
				if row[c] == '#' {
					b |= 1 << (4 - c)
				}
			}
			g[r] = b
		}
		font5x7[ch] = g
	}
}

